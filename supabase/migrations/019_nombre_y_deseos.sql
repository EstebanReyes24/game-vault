-- =====================================================================
-- Paindex Vault — Migración 019: elegir nombre una vez y lista de deseos
--
-- 1. Quien entra con Google recibe un nombre sacado de su correo. Puede cambiarlo
--    UNA sola vez desde "Mi perfil" (elegir_nombre). Después queda fijo para no
--    romper los enlaces que comparta.
-- 2. Lista de deseos: juegos que quieres, con su precio en tiendas de PC (CheapShark)
--    y fecha de salida. Avisos "bajó de precio" y "ya salió" en la campana.
--
-- CÓMO APLICARLA: Supabase → SQL Editor → New query → pegar → Run.
-- =====================================================================
begin;

-- 1. Nombre elegido
alter table public.profiles add column if not exists nombre_elegido boolean not null default false;

create or replace function public.elegir_nombre(p_nuevo text)
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  uid uuid := auth.uid();
  limpio text := lower(btrim(coalesce(p_nuevo, '')));
begin
  if uid is null then raise exception 'Inicia sesión.'; end if;
  if limpio !~ '^[a-z0-9_]{3,20}$' then
    raise exception 'El nombre debe tener de 3 a 20 caracteres: letras minúsculas, números y _.';
  end if;
  if (select nombre_elegido from public.profiles where id = uid) then
    raise exception 'Ya elegiste tu nombre: no se puede cambiar otra vez.';
  end if;
  if exists (select 1 from public.profiles where username = limpio and id <> uid) then
    raise exception 'Ese nombre ya está en uso.';
  end if;
  update public.profiles set username = limpio, nombre_elegido = true where id = uid;
  return limpio;
end;
$$;
revoke all on function public.elegir_nombre(text) from public;
grant execute on function public.elegir_nombre(text) to authenticated;

-- Quien se registró con correo ya eligió su nombre al crear la cuenta
create or replace function public.marcar_nombre_elegido()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if (select raw_user_meta_data ? 'username' from auth.users where id = new.id) then
    new.nombre_elegido := true;
  end if;
  return new;
end;
$$;
drop trigger if exists marcar_nombre_elegido on public.profiles;
create trigger marcar_nombre_elegido before insert on public.profiles
  for each row execute function public.marcar_nombre_elegido();
update public.profiles p set nombre_elegido = true
  from auth.users u where u.id = p.id and u.raw_user_meta_data ? 'username' and not p.nombre_elegido;

-- 2. Lista de deseos
create table if not exists public.wishlist (
  id            bigint generated by default as identity primary key,
  user_id       uuid not null references auth.users(id) on delete cascade,
  titulo        text not null check (char_length(titulo) between 1 and 150),
  portada       text check (portada is null or portada ~ '^https://[^\s"''<>]+$'),
  cheapshark_id text check (cheapshark_id is null or cheapshark_id ~ '^[0-9]{1,12}$'),
  steam_appid   integer,
  fecha_salida  date,
  precio_objetivo numeric(7,2) check (precio_objetivo is null or precio_objetivo between 0 and 1000),
  ultimo_precio numeric(7,2),
  precio_normal numeric(7,2),
  tienda        text check (tienda is null or char_length(tienda) <= 40),
  avisado_precio numeric(7,2),
  avisado_salida boolean not null default false,
  creado        timestamptz not null default now(),
  unique (user_id, titulo)
);
alter table public.wishlist enable row level security;
drop policy if exists "Mi lista de deseos" on public.wishlist;
create policy "Mi lista de deseos" on public.wishlist for all
  using (auth.uid() = user_id) with check (auth.uid() = user_id);

create or replace function public.tope_deseos()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if (select count(*) from public.wishlist where user_id = new.user_id) >= 300 then
    raise exception 'Tu lista de deseos llegó al máximo de 300 juegos.';
  end if;
  return new;
end;
$$;
drop trigger if exists tope_deseos on public.wishlist;
create trigger tope_deseos before insert on public.wishlist
  for each row execute function public.tope_deseos();

-- Avisos de precio y de salida (cada uno se los crea a sí mismo al abrir su lista)
alter table public.notifications drop constraint if exists notifications_kind_check;
alter table public.notifications add constraint notifications_kind_check
  check (kind in ('seguidor', 'comentario', 'precio', 'salida'));

create or replace function public.avisar_deseo(p_id bigint, p_tipo text, p_texto text)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare d public.wishlist;
begin
  select * into d from public.wishlist where id = p_id and user_id = auth.uid();
  if d.id is null or p_tipo not in ('precio', 'salida') then return; end if;
  if p_tipo = 'precio' then
    if d.ultimo_precio is null or (d.avisado_precio is not null and d.ultimo_precio >= d.avisado_precio) then return; end if;
    update public.wishlist set avisado_precio = d.ultimo_precio where id = d.id;
  else
    if d.avisado_salida then return; end if;
    update public.wishlist set avisado_salida = true where id = d.id;
  end if;
  insert into public.notifications (user_id, kind, actor, texto, enlace)
  values (auth.uid(), p_tipo, 'Paindex', left(p_texto, 300), '/estante?deseos=1');
end;
$$;
revoke all on function public.avisar_deseo(bigint, text, text) from public;
grant execute on function public.avisar_deseo(bigint, text, text) to authenticated;

commit;
