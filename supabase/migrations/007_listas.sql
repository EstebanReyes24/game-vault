-- =====================================================================
-- Paindex Vault — Migración 007: listas de juegos
--
-- Cada usuario puede armar listas ("Terror que sí da miedo", "Para jugar
-- con amigos"...) con juegos de su estante, en el orden que quiera.
-- Las listas se ven si el estante es público.
-- Límites: 30 listas por usuario y 50 juegos por lista.
--
-- CÓMO APLICARLA: Supabase → SQL Editor → New query → pegar → Run.
-- Se puede ejecutar varias veces sin problema.
-- =====================================================================

begin;

create table if not exists public.lists (
  id          bigint generated by default as identity primary key,
  user_id     uuid not null references auth.users(id) on delete cascade,
  title       text not null check (char_length(btrim(title)) between 1 and 80),
  description text check (description is null or char_length(description) <= 400),
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);
create index if not exists lists_user_idx on public.lists (user_id, updated_at desc);

create table if not exists public.list_items (
  list_id    bigint not null references public.lists(id) on delete cascade,
  position   int not null check (position between 0 and 49),
  game_title text not null check (char_length(game_title) between 1 and 200),
  cover_url  text check (cover_url is null or cover_url ~ '^https://[^\s"''<>]+$'),
  rating     numeric(3,1),
  note       text check (note is null or char_length(note) <= 200),
  primary key (list_id, position)
);

alter table public.lists enable row level security;
alter table public.list_items enable row level security;

create or replace function public.dueno_publico_o_propio(dueno uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select dueno = auth.uid()
      or exists (select 1 from public.profiles p where p.id = dueno and p.is_public);
$$;

drop policy if exists "Ver listas" on public.lists;
create policy "Ver listas" on public.lists for select using (public.dueno_publico_o_propio(user_id));
drop policy if exists "Gestionar mis listas" on public.lists;
create policy "Gestionar mis listas" on public.lists for all
  using (auth.uid() = user_id) with check (auth.uid() = user_id);

drop policy if exists "Ver juegos de listas" on public.list_items;
create policy "Ver juegos de listas" on public.list_items for select
  using (exists (select 1 from public.lists l where l.id = list_id and public.dueno_publico_o_propio(l.user_id)));
drop policy if exists "Gestionar juegos de mis listas" on public.list_items;
create policy "Gestionar juegos de mis listas" on public.list_items for all
  using (exists (select 1 from public.lists l where l.id = list_id and l.user_id = auth.uid()))
  with check (exists (select 1 from public.lists l where l.id = list_id and l.user_id = auth.uid()));

-- Tope de listas por usuario y fecha de actualización
create or replace function public.before_list_insert()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if (select count(*) from public.lists where user_id = new.user_id) >= 30 then
    raise exception 'Llegaste al máximo de 30 listas.';
  end if;
  new.title := btrim(new.title);
  return new;
end;
$$;
drop trigger if exists lists_before_insert on public.lists;
create trigger lists_before_insert before insert on public.lists
  for each row execute function public.before_list_insert();

create or replace function public.touch_list()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  update public.lists set updated_at = now() where id = coalesce(new.list_id, old.list_id);
  return null;
end;
$$;
drop trigger if exists list_items_touch on public.list_items;
create trigger list_items_touch after insert or update or delete on public.list_items
  for each row execute function public.touch_list();

commit;
