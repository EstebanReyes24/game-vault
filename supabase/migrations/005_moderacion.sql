-- =====================================================================
-- Paindex Vault — Migración 005: moderación de comentarios
--
-- - Cualquiera con cuenta puede reportar un comentario (una vez cada uno).
-- - Con 3 reportes de personas distintas el comentario se oculta solo
--   hasta que el admin lo revise.
-- - El admin puede ocultar/mostrar, borrar, descartar reportes y
--   bloquear usuarios. Un usuario bloqueado no puede comentar.
--
-- CÓMO APLICARLA: Supabase → SQL Editor → New query → pegar → Run.
-- Se puede ejecutar varias veces sin problema.
-- =====================================================================

begin;

create or replace function public.es_admin()
returns boolean
language sql
stable
as $$
  select coalesce(auth.jwt() -> 'app_metadata' ->> 'role', '') = 'admin';
$$;

-- 1. Comentarios ocultos
alter table public.post_comments add column if not exists hidden boolean not null default false;

drop policy if exists "Comentarios públicos" on public.post_comments;
create policy "Comentarios públicos" on public.post_comments for select
  using (not hidden or auth.uid() = user_id or public.es_admin());

drop policy if exists "Admin modera comentarios" on public.post_comments;
create policy "Admin modera comentarios" on public.post_comments for update
  using (public.es_admin()) with check (public.es_admin());

-- 2. Usuarios bloqueados
create table if not exists public.banned_users (
  user_id    uuid primary key references auth.users(id) on delete cascade,
  reason     text,
  created_at timestamptz not null default now()
);
alter table public.banned_users enable row level security;
drop policy if exists "Admin gestiona bloqueos" on public.banned_users;
create policy "Admin gestiona bloqueos" on public.banned_users for all
  using (public.es_admin()) with check (public.es_admin());

-- security definer: la tabla de bloqueos solo la puede leer el admin
create or replace function public.esta_bloqueado(uid uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (select 1 from public.banned_users where user_id = uid);
$$;
revoke all on function public.esta_bloqueado(uuid) from public;
grant execute on function public.esta_bloqueado(uuid) to authenticated;

drop policy if exists "Usuarios comentan" on public.post_comments;
create policy "Usuarios comentan" on public.post_comments for insert
  with check (auth.uid() = user_id and not public.esta_bloqueado(auth.uid()));

-- 3. Reportes
create table if not exists public.comment_reports (
  id          bigint generated by default as identity primary key,
  comment_id  bigint not null references public.post_comments(id) on delete cascade,
  reporter_id uuid not null references auth.users(id) on delete cascade,
  reason      text check (reason is null or char_length(reason) <= 200),
  created_at  timestamptz not null default now(),
  unique (comment_id, reporter_id)
);
alter table public.comment_reports enable row level security;

drop policy if exists "Usuarios reportan" on public.comment_reports;
create policy "Usuarios reportan" on public.comment_reports for insert
  with check (auth.uid() = reporter_id);
drop policy if exists "Admin ve reportes" on public.comment_reports;
create policy "Admin ve reportes" on public.comment_reports for select
  using (public.es_admin());
drop policy if exists "Admin descarta reportes" on public.comment_reports;
create policy "Admin descarta reportes" on public.comment_reports for delete
  using (public.es_admin());

-- No se puede reportar el propio comentario; con 3 reportes se oculta
create or replace function public.after_comment_report()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  autor uuid;
  total int;
begin
  select user_id into autor from public.post_comments where id = new.comment_id;
  if autor = new.reporter_id then
    raise exception 'No puedes reportar tu propio comentario.';
  end if;
  select count(*) into total from public.comment_reports where comment_id = new.comment_id;
  if total >= 3 then
    update public.post_comments set hidden = true where id = new.comment_id;
  end if;
  return new;
end;
$$;

drop trigger if exists comment_reports_after_insert on public.comment_reports;
create trigger comment_reports_after_insert
  after insert on public.comment_reports
  for each row execute function public.after_comment_report();

-- 4. Bandeja de moderación (solo admin): comentarios con reportes u ocultos
create or replace function public.moderacion_pendiente()
returns table (
  comment_id bigint,
  comment text,
  hidden boolean,
  created_at timestamptz,
  autor_id uuid,
  autor text,
  autor_bloqueado boolean,
  post_id bigint,
  post_titulo text,
  reportes bigint,
  motivos text[]
)
language sql
stable
security definer
set search_path = public
as $$
  select c.id, c.comment, c.hidden, c.created_at, c.user_id, c.username,
         exists (select 1 from public.banned_users b where b.user_id = c.user_id),
         c.post_id, p.title,
         count(r.id),
         array_remove(array_agg(r.reason), null)
  from public.post_comments c
  join public.posts p on p.id = c.post_id
  left join public.comment_reports r on r.comment_id = c.id
  where public.es_admin()
  group by c.id, p.title
  having count(r.id) > 0 or c.hidden
  order by c.hidden desc, count(r.id) desc, c.created_at desc
  limit 100;
$$;

revoke all on function public.moderacion_pendiente() from public;
grant execute on function public.moderacion_pendiente() to authenticated;

commit;
