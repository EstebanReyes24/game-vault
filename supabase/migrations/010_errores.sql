-- =====================================================================
-- Paindex Vault — Migración 010: registro de errores de la web
--
-- Cuando algo falla en el navegador de un visitante (un error de JavaScript
-- o una promesa sin manejar), la web lo anota aquí. El admin lo ve en el
-- panel de Moderación → "Errores". Se guardan 30 días y como máximo 300
-- por hora, para que nadie pueda llenar la base de datos.
--
-- CÓMO APLICARLA: Supabase → SQL Editor → New query → pegar → Run.
-- Requiere 009 (es_admin). Se puede ejecutar varias veces sin problema.
-- =====================================================================

begin;

create table if not exists public.client_errors (
  id         bigint generated by default as identity primary key,
  message    text not null,
  source     text,
  page       text,
  line       int,
  user_agent text,
  user_id    uuid,
  created_at timestamptz not null default now()
);
create index if not exists client_errors_recent_idx on public.client_errors (created_at desc);
alter table public.client_errors enable row level security;
-- Sin políticas: nadie lee ni escribe directo. Solo por las funciones de abajo.

create or replace function public.registrar_error(mensaje text, fuente text, pagina text, linea int, navegador text)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if (select count(*) from public.client_errors where created_at > now() - interval '1 hour') >= 300 then
    return;
  end if;
  insert into public.client_errors (message, source, page, line, user_agent, user_id)
  values (left(coalesce(mensaje, '(sin mensaje)'), 500), left(fuente, 300), left(pagina, 300), linea, left(navegador, 300), auth.uid());
  -- limpieza de lo viejo, de vez en cuando
  if random() < 0.05 then
    delete from public.client_errors where created_at < now() - interval '30 days';
  end if;
end;
$$;

create or replace function public.errores_recientes()
returns table (message text, veces bigint, ultima timestamptz, pagina text, source text, line int, navegador text)
language sql
stable
security definer
set search_path = public
as $$
  select message, count(*), max(created_at),
         (array_agg(page order by created_at desc))[1],
         (array_agg(source order by created_at desc))[1],
         (array_agg(line order by created_at desc))[1],
         (array_agg(user_agent order by created_at desc))[1]
  from public.client_errors
  where public.es_admin() and created_at > now() - interval '7 days'
  group by message
  order by max(created_at) desc
  limit 50;
$$;

revoke all on function public.registrar_error(text, text, text, int, text) from public;
revoke all on function public.errores_recientes() from public;
grant execute on function public.registrar_error(text, text, text, int, text) to anon, authenticated;
grant execute on function public.errores_recientes() to authenticated;

commit;
