-- =====================================================================
-- Paindex Vault — Migración 006: seguir jugadores y actividad
--
-- - follows: quién sigue a quién (solo se puede seguir estantes públicos).
-- - activity: se llena sola cuando alguien empieza, termina, platina o
--   califica un juego. Solo se muestra la de estantes públicos.
-- - Funciones para la portada y el perfil: actividad_reciente() y
--   resumen_social().
--
-- CÓMO APLICARLA: Supabase → SQL Editor → New query → pegar → Run.
-- Se puede ejecutar varias veces sin problema.
-- =====================================================================

begin;

-- 1. Seguir
create table if not exists public.follows (
  follower_id uuid not null references auth.users(id) on delete cascade,
  followed_id uuid not null references auth.users(id) on delete cascade,
  created_at  timestamptz not null default now(),
  primary key (follower_id, followed_id),
  constraint follows_no_self check (follower_id <> followed_id)
);
create index if not exists follows_followed_idx on public.follows (followed_id);
alter table public.follows enable row level security;

drop policy if exists "Cada uno ve a quién sigue" on public.follows;
create policy "Cada uno ve a quién sigue" on public.follows for select
  using (auth.uid() = follower_id);
drop policy if exists "Seguir estantes públicos" on public.follows;
create policy "Seguir estantes públicos" on public.follows for insert
  with check (
    auth.uid() = follower_id
    and exists (select 1 from public.profiles p where p.id = followed_id and p.is_public)
  );
drop policy if exists "Dejar de seguir" on public.follows;
create policy "Dejar de seguir" on public.follows for delete
  using (auth.uid() = follower_id);

-- 2. Actividad
create table if not exists public.activity (
  id         bigint generated by default as identity primary key,
  user_id    uuid not null references auth.users(id) on delete cascade,
  kind       text not null check (kind in ('jugando', 'terminado', 'platino', 'nota')),
  game_title text not null,
  cover_url  text,
  rating     numeric(3,1),
  created_at timestamptz not null default now()
);
create index if not exists activity_recent_idx on public.activity (created_at desc);
create index if not exists activity_user_idx on public.activity (user_id, created_at desc);
alter table public.activity enable row level security;
-- Nadie escribe a mano: solo el disparador. La lectura va por actividad_reciente().
drop policy if exists "Actividad propia" on public.activity;
create policy "Actividad propia" on public.activity for select using (auth.uid() = user_id);

create or replace function public.after_game_change()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  tipo text;
  recientes int;
  portada text := case when new.cover_url ~ '^https://' then new.cover_url end;
begin
  if tg_op = 'INSERT' or new.status is distinct from old.status then
    tipo := case new.status
      when 'playing' then 'jugando'
      when 'platinum' then 'platino'
      when 'completed' then 'terminado'
      when 'extras' then 'terminado'
    end;
  end if;
  if tipo is null and tg_op = 'UPDATE'
     and coalesce(new.rating, 0) > 0 and new.rating is distinct from old.rating then
    tipo := 'nota';
  end if;
  if tipo is null then return new; end if;

  -- Importaciones masivas (Steam, JSON) no inundan la actividad
  select count(*) into recientes from public.activity
   where user_id = new.user_id and created_at > now() - interval '2 minutes';
  if recientes >= 5 then return new; end if;

  -- Una calificación justo después de terminar el mismo juego no se repite
  if tipo = 'nota' and exists (
    select 1 from public.activity
     where user_id = new.user_id and game_title = new.title and created_at > now() - interval '10 minutes'
  ) then
    update public.activity set rating = new.rating
     where id = (select id from public.activity
                  where user_id = new.user_id and game_title = new.title
                  order by created_at desc, id desc limit 1);
    return new;
  end if;

  insert into public.activity (user_id, kind, game_title, cover_url, rating)
  values (new.user_id, tipo, new.title, portada, nullif(new.rating, 0));
  return new;
end;
$$;

drop trigger if exists games_after_change on public.games;
create trigger games_after_change
  after insert or update on public.games
  for each row execute function public.after_game_change();

-- 3. Lectura para la web
create or replace function public.actividad_reciente(solo_seguidos boolean default false, limite int default 20)
returns table (id bigint, username text, kind text, game_title text, cover_url text, rating numeric, created_at timestamptz)
language sql
stable
security definer
set search_path = public
as $$
  select a.id, p.username, a.kind, a.game_title, a.cover_url, a.rating, a.created_at
  from public.activity a
  join public.profiles p on p.id = a.user_id and p.is_public
  where not solo_seguidos
     or a.user_id in (select followed_id from public.follows where follower_id = auth.uid())
  order by a.created_at desc
  limit least(greatest(limite, 1), 50);
$$;

create or replace function public.resumen_social(usuario text)
returns table (seguidores bigint, siguiendo bigint, lo_sigo boolean)
language sql
stable
security definer
set search_path = public
as $$
  select
    (select count(*) from public.follows f where f.followed_id = p.id),
    (select count(*) from public.follows f where f.follower_id = p.id),
    exists (select 1 from public.follows f where f.followed_id = p.id and f.follower_id = auth.uid())
  from public.profiles p
  where p.username = lower(usuario) and p.is_public;
$$;

revoke all on function public.actividad_reciente(boolean, int) from public;
revoke all on function public.resumen_social(text) from public;
grant execute on function public.actividad_reciente(boolean, int) to anon, authenticated;
grant execute on function public.resumen_social(text) to anon, authenticated;

commit;
