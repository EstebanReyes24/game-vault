-- =====================================================================
-- Paindex Vault — Migración 008: reseñas de usuarios
--
-- - Cada usuario escribe una reseña por juego de su estante (50 a 5000
--   caracteres), con aviso de spoilers opcional.
-- - Se ven en su perfil si el estante es público.
-- - El admin puede destacar reseñas para la portada.
-- - Se pueden reportar; con 3 reportes se ocultan hasta que el admin revise.
-- - Publicar una reseña aparece en la actividad.
--
-- CÓMO APLICARLA: Supabase → SQL Editor → New query → pegar → Run.
-- Requiere 005 (moderación) y 006 (actividad). Se puede ejecutar varias veces.
-- =====================================================================

begin;

create table if not exists public.reviews (
  id         bigint generated by default as identity primary key,
  user_id    uuid not null references auth.users(id) on delete cascade,
  game_title text not null check (char_length(game_title) between 1 and 200),
  cover_url  text check (cover_url is null or cover_url ~ '^https://[^\s"''<>]+$'),
  rating     numeric(3,1) check (rating is null or rating between 1 and 10),
  body       text not null check (char_length(btrim(body)) between 50 and 5000),
  spoilers   boolean not null default false,
  featured   boolean not null default false,
  hidden     boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, game_title)
);
create index if not exists reviews_user_idx on public.reviews (user_id, created_at desc);
create index if not exists reviews_featured_idx on public.reviews (featured, created_at desc) where featured;
alter table public.reviews enable row level security;

drop policy if exists "Ver reseñas" on public.reviews;
create policy "Ver reseñas" on public.reviews for select using (
  auth.uid() = user_id
  or public.es_admin()
  or (not hidden and exists (select 1 from public.profiles p where p.id = user_id and p.is_public))
);
drop policy if exists "Escribir mis reseñas" on public.reviews;
create policy "Escribir mis reseñas" on public.reviews for insert
  with check (auth.uid() = user_id and not public.esta_bloqueado(auth.uid()));
drop policy if exists "Editar mis reseñas" on public.reviews;
create policy "Editar mis reseñas" on public.reviews for update
  using (auth.uid() = user_id or public.es_admin())
  with check (auth.uid() = user_id or public.es_admin());
drop policy if exists "Borrar reseñas" on public.reviews;
create policy "Borrar reseñas" on public.reviews for delete
  using (auth.uid() = user_id or public.es_admin());

-- El autor no puede destacarse ni desocultarse solo; el texto se limpia
create or replace function public.before_review_write()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  recientes int;
begin
  new.body := btrim(new.body);
  new.game_title := btrim(new.game_title);
  -- pg_trigger_depth() > 1: cambio hecho por otro disparador (p. ej. ocultar por reportes)
  if not public.es_admin() and pg_trigger_depth() = 1 then
    if tg_op = 'INSERT' then
      new.featured := false;
      new.hidden := false;
      select count(*) into recientes from public.reviews
       where user_id = new.user_id and created_at > now() - interval '10 minutes';
      if recientes >= 5 then
        raise exception 'Estás publicando muy rápido. Espera unos minutos.';
      end if;
    else
      new.featured := old.featured;
      new.hidden := old.hidden;
    end if;
  end if;
  if tg_op = 'UPDATE' and (new.body is distinct from old.body or new.rating is distinct from old.rating or new.spoilers is distinct from old.spoilers) then
    new.updated_at := now();
  end if;
  return new;
end;
$$;
drop trigger if exists reviews_before_write on public.reviews;
create trigger reviews_before_write before insert or update on public.reviews
  for each row execute function public.before_review_write();

-- Actividad: publicar reseña
alter table public.activity drop constraint if exists activity_kind_check;
alter table public.activity add constraint activity_kind_check
  check (kind in ('jugando', 'terminado', 'platino', 'nota', 'resena'));

create or replace function public.after_review_insert()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.activity (user_id, kind, game_title, cover_url, rating)
  values (new.user_id, 'resena', new.game_title, new.cover_url, new.rating);
  return new;
end;
$$;
drop trigger if exists reviews_after_insert on public.reviews;
create trigger reviews_after_insert after insert on public.reviews
  for each row execute function public.after_review_insert();

-- Reportes de reseñas
create table if not exists public.review_reports (
  id          bigint generated by default as identity primary key,
  review_id   bigint not null references public.reviews(id) on delete cascade,
  reporter_id uuid not null references auth.users(id) on delete cascade,
  reason      text check (reason is null or char_length(reason) <= 200),
  created_at  timestamptz not null default now(),
  unique (review_id, reporter_id)
);
alter table public.review_reports enable row level security;
drop policy if exists "Usuarios reportan reseñas" on public.review_reports;
create policy "Usuarios reportan reseñas" on public.review_reports for insert with check (auth.uid() = reporter_id);
drop policy if exists "Admin ve reportes de reseñas" on public.review_reports;
create policy "Admin ve reportes de reseñas" on public.review_reports for select using (public.es_admin());
drop policy if exists "Admin descarta reportes de reseñas" on public.review_reports;
create policy "Admin descarta reportes de reseñas" on public.review_reports for delete using (public.es_admin());

create or replace function public.after_review_report()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if (select user_id from public.reviews where id = new.review_id) = new.reporter_id then
    raise exception 'No puedes reportar tu propia reseña.';
  end if;
  if (select count(*) from public.review_reports where review_id = new.review_id) >= 3 then
    update public.reviews set hidden = true where id = new.review_id;
  end if;
  return new;
end;
$$;
drop trigger if exists review_reports_after_insert on public.review_reports;
create trigger review_reports_after_insert after insert on public.review_reports
  for each row execute function public.after_review_report();

-- Lectura para la web
create or replace function public.resenas_destacadas(limite int default 3)
returns table (id bigint, username text, game_title text, cover_url text, rating numeric, body text, spoilers boolean, created_at timestamptz)
language sql
stable
security definer
set search_path = public
as $$
  select r.id, p.username, r.game_title, r.cover_url, r.rating, r.body, r.spoilers, r.created_at
  from public.reviews r
  join public.profiles p on p.id = r.user_id and p.is_public
  where r.featured and not r.hidden
  order by r.created_at desc
  limit least(greatest(limite, 1), 12);
$$;

create or replace function public.moderacion_resenas()
returns table (review_id bigint, game_title text, body text, hidden boolean, featured boolean, autor_id uuid, autor text,
               autor_bloqueado boolean, reportes bigint, motivos text[], created_at timestamptz)
language sql
stable
security definer
set search_path = public
as $$
  select r.id, r.game_title, r.body, r.hidden, r.featured, r.user_id, p.username,
         public.esta_bloqueado(r.user_id), count(x.id), array_remove(array_agg(x.reason), null), r.created_at
  from public.reviews r
  join public.profiles p on p.id = r.user_id
  left join public.review_reports x on x.review_id = r.id
  where public.es_admin()
  group by r.id, p.username
  having count(x.id) > 0 or r.hidden
  order by r.hidden desc, count(x.id) desc, r.created_at desc
  limit 100;
$$;

revoke all on function public.resenas_destacadas(int) from public;
revoke all on function public.moderacion_resenas() from public;
grant execute on function public.resenas_destacadas(int) to anon, authenticated;
grant execute on function public.moderacion_resenas() to authenticated;

