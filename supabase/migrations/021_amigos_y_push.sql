-- =====================================================================
-- 021 · Avisos de la gente que sigues y notificaciones en el teléfono
-- 1. Aviso "amigo": alguien que sigues platinó o terminó un juego (máx. 3 por persona y día)
-- 2. push_subs: los dispositivos donde cada cuenta activó las notificaciones
-- 3. privado.ajustes: el secreto compartido con /api/push y su dirección (sin acceso desde la web)
-- 4. Cada aviso nuevo se manda a /api/push (pg_net), que lo envía a los dispositivos
-- =====================================================================
begin;

create extension if not exists pg_net with schema extensions;

-- 1. Avisos de amigos ---------------------------------------------------
alter table public.notifications drop constraint if exists notifications_kind_check;
alter table public.notifications add constraint notifications_kind_check
  check (kind in ('seguidor', 'comentario', 'precio', 'salida', 'amigo', 'prueba'));

create or replace function public.avisar_amigos()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  quien text;
  publico boolean;
  verbo text;
begin
  if new.kind not in ('platino', 'terminado') then return new; end if;
  select username, is_public into quien, publico from profiles where id = new.user_id;
  if quien is null or not publico then return new; end if;
  verbo := case new.kind when 'platino' then 'platinó' else 'terminó' end;
  insert into notifications (user_id, kind, actor, texto, enlace)
  select f.follower_id, 'amigo', quien, verbo || ' «' || left(new.game_title, 120) || '»', '/u/' || quien
    from follows f
   where f.followed_id = new.user_id
     and f.follower_id <> new.user_id
     and (select count(*) from notifications n
           where n.user_id = f.follower_id and n.kind = 'amigo' and n.actor = quien
             and n.created_at > now() - interval '1 day') < 3;
  return new;
end;
$$;
drop trigger if exists avisar_amigos on public.activity;
create trigger avisar_amigos after insert on public.activity
  for each row execute function public.avisar_amigos();

-- 2. Dispositivos con notificaciones ------------------------------------
create table if not exists public.push_subs (
  id       bigint generated by default as identity primary key,
  user_id  uuid not null default auth.uid() references auth.users(id) on delete cascade,
  endpoint text not null unique check (endpoint ~ '^https://' and char_length(endpoint) <= 1000),
  p256dh   text not null check (char_length(p256dh) <= 200),
  auth     text not null check (char_length(auth) <= 100),
  creado   timestamptz not null default now()
);
create index if not exists push_subs_user_idx on public.push_subs (user_id);
alter table public.push_subs enable row level security;
drop policy if exists "Mis dispositivos" on public.push_subs;
create policy "Mis dispositivos" on public.push_subs for select using (auth.uid() = user_id);
drop policy if exists "Añadir mi dispositivo" on public.push_subs; -- se añade con registrar_push()
drop policy if exists "Quitar mi dispositivo" on public.push_subs;
create policy "Quitar mi dispositivo" on public.push_subs for delete using (auth.uid() = user_id);
grant select, delete on public.push_subs to authenticated;

-- Activar en este dispositivo (si el navegador estaba con otra cuenta, pasa a esta)
create or replace function public.registrar_push(p_endpoint text, p_p256dh text, p_auth text)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if auth.uid() is null then raise exception 'Inicia sesión para activar las notificaciones'; end if;
  if p_endpoint !~ '^https://(fcm\.googleapis\.com|updates\.push\.services\.mozilla\.com|push\.services\.mozilla\.com|[a-z0-9.-]+\.push\.apple\.com|[a-z0-9.-]+\.notify\.windows\.com)/' then
    raise exception 'Ese navegador no es compatible con las notificaciones';
  end if;
  delete from push_subs where endpoint = p_endpoint;
  if (select count(*) from push_subs where user_id = auth.uid()) >= 10 then
    delete from push_subs where id = (select id from push_subs where user_id = auth.uid() order by creado limit 1);
  end if;
  insert into push_subs (user_id, endpoint, p256dh, auth) values (auth.uid(), p_endpoint, p_p256dh, p_auth);
end;
$$;
revoke all on function public.registrar_push(text, text, text) from public;
grant execute on function public.registrar_push(text, text, text) to authenticated;

-- 3. Ajustes privados (solo se cambian desde el panel de Supabase) -------
create schema if not exists privado;
revoke all on schema privado from public, anon, authenticated;
create table if not exists privado.ajustes (clave text primary key, valor text not null);
revoke all on privado.ajustes from public, anon, authenticated;

-- /api/push pide los dispositivos de una cuenta presentando el secreto
create or replace function public.push_destinos(p_secreto text, p_user uuid)
returns table (endpoint text, p256dh text, auth text)
language sql
stable
security definer
set search_path = public
as $$
  select s.endpoint, s.p256dh, s.auth from push_subs s
   where s.user_id = p_user
     and exists (select 1 from privado.ajustes a where a.clave = 'push_secreto' and a.valor = p_secreto and length(p_secreto) >= 32);
$$;
revoke all on function public.push_destinos(text, uuid) from public;
grant execute on function public.push_destinos(text, uuid) to anon, authenticated;

-- …y borra los que el navegador ya dio de baja
create or replace function public.push_olvidar(p_secreto text, p_endpoint text)
returns void
language sql
security definer
set search_path = public
as $$
  delete from push_subs
   where endpoint = p_endpoint
     and exists (select 1 from privado.ajustes a where a.clave = 'push_secreto' and a.valor = p_secreto and length(p_secreto) >= 32);
$$;
revoke all on function public.push_olvidar(text, text) from public;
grant execute on function public.push_olvidar(text, text) to anon, authenticated;

-- Botón "Probar": un aviso para ti mismo (como mucho uno por minuto)
create or replace function public.probar_push()
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if auth.uid() is null then raise exception 'Inicia sesión'; end if;
  if exists (select 1 from notifications where user_id = auth.uid() and kind = 'prueba' and created_at > now() - interval '1 minute') then
    raise exception 'Espera un minuto antes de otra prueba';
  end if;
  insert into notifications (user_id, kind, texto, enlace)
  values (auth.uid(), 'prueba', '¡Las notificaciones funcionan en este dispositivo!', '/estante');
end;
$$;
revoke all on function public.probar_push() from public;
grant execute on function public.probar_push() to authenticated;

-- 4. Cada aviso nuevo va al teléfono -----------------------------------
create or replace function public.enviar_push()
returns trigger
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  url text;
  secreto text;
begin
  if not exists (select 1 from push_subs where user_id = new.user_id) then return new; end if;
  select valor into url from privado.ajustes where clave = 'push_url';
  select valor into secreto from privado.ajustes where clave = 'push_secreto';
  if url is null or secreto is null then return new; end if;
  perform net.http_post(
    url := url,
    body := jsonb_build_object('user_id', new.user_id, 'kind', new.kind, 'actor', new.actor, 'texto', new.texto, 'enlace', new.enlace, 'id', new.id),
    headers := jsonb_build_object('Content-Type', 'application/json', 'x-push-secreto', secreto),
    timeout_milliseconds := 5000
  );
  return new;
exception when others then
  return new; -- un fallo al enviar nunca impide guardar el aviso
end;
$$;
drop trigger if exists enviar_push on public.notifications;
create trigger enviar_push after insert on public.notifications
  for each row execute function public.enviar_push();

commit;
